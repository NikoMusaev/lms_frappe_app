"""Включает запись языка `ru` (#42).

`Why:` Frappe заводит русский **выключенным** — в `frappe/geo/languages.csv`
у него `enabled=0`, тогда как у английского, немецкого и французского `1`.
Последствий два, и оба выглядят как «русского языка на платформе нет»:

- в профиле пользователя и в системных настройках его нет в списке: поле
  ссылается на `Language` и показывает только включённые;
- `get_all_languages()` отдаёт только включённые, поэтому язык не подберётся
  и по заголовку `Accept-Language` — русскоязычный браузер получит английский
  интерфейс.

Предыдущий патч записал `ru` в системные настройки напрямую, минуя
валидацию, поэтому серверные страницы уже на русском — а выбрать язык
руками по-прежнему нельзя. Этот патч чинит вторую половину.
"""

import frappe

ЯЗЫК = "ru"


def execute():
	if not frappe.db.exists("Language", ЯЗЫК):
		return
	frappe.db.set_value("Language", ЯЗЫК, "enabled", 1)
	# Список языков кэшируется на стороне клиента и сервера: без сброса
	# селектор останется прежним до перезапуска.
	frappe.client_cache.delete_value("languages")
	frappe.cache.delete_value("languages_with_name")
