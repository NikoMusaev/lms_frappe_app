"""Разница «было → стало» для кабинета автора.

Автор проверяет «сделано» и правки агента по разнице, а не перечитывая раздел
(lms-high-time/learning-services#271). Модуль к базе не ходит: только текст.

Единица сравнения — абзац, а в режиме строк — строка: пункт списка, строка
вопроса. Абзацы сопоставляются между собой; внутри изменённого — сравнение по
словам, чтобы правка в одно слово не выглядела новым абзацем. Неизменённое
вокруг правки сворачивается: иначе оно заслоняет её.

Итог — `{"state": "same"}` или `{"state": "changed", "rewritten", "blocks"}`;
блоки:

- `{"kind": "same", "text"}` — абзац без изменений;
- `{"kind": "gap", "texts"}` — свёрнутые абзацы без изменений;
- `{"kind": "changed", "parts": [[знак, текст], …]}` — `=` общее, `-` было,
  `+` стало;
- `{"kind": "added", "text"}`, `{"kind": "removed", "text"}`.
"""

import difflib
import re

РЕЖИМ_ТЕКСТ = "text"
РЕЖИМ_СТРОКИ = "lines"

#: Меньше этой доли общего текста — «переписан почти целиком»: зачёркнутый
#: сплошняком текст читать тяжелее, чем новый целиком.
ПОРОГ_ПЕРЕПИСАН = 1 / 3
#: Абзацы на одном месте считаются правкой одного, если слов общих хотя бы
#: столько; иначе это удалённый абзац и новый.
ПОРОГ_ПАРЫ = 0.4
#: Сколько неизменённых абзацев оставлять вокруг правки.
КОНТЕКСТ = 1

#: Слова, знаки и пробелы — отдельно: иначе «меру.» и «меру» не совпадали, и
#: правка в конце предложения выглядела заменой слова целиком.
_ЛЕКСЕМЫ = re.compile(r"\s+|\w+|[^\w\s]")
#: Начало пункта списка или строки таблицы markdown.
_ПУНКТ = re.compile(r"^\s*(?:[-*+]\s|\d+[.)]\s|\|)")


def единицы(текст: str | None, режим: str = РЕЖИМ_ТЕКСТ) -> list[str]:
	"""Абзацы — по пустым строкам, или строки — в режиме строк. Пробелы по
	краям строк правкой не считаются.

	Список или таблица в тексте — тоже абзац без пустых строк, но сравнивается
	по строкам: иначе правка одной строки показывала бы таблицу целиком.
	"""
	текст = (текст or "").replace("\r\n", "\n")
	части = текст.split("\n") if режим == РЕЖИМ_СТРОКИ else re.split(r"\n\s*\n", текст)
	чистые = ("\n".join(строка.rstrip() for строка in часть.split("\n")).strip() for часть in части)
	итог: list[str] = []
	for часть in чистые:
		if not часть:
			continue
		строки = часть.split("\n")
		if len(строки) > 1 and _ПУНКТ.match(строки[0]):
			итог += [строка for строка in строки if строка.strip()]
		else:
			итог.append(часть)
	return итог


def разница(было: str | None, стало: str | None, режим: str = РЕЖИМ_ТЕКСТ) -> dict:
	старые, новые = единицы(было, режим), единицы(стало, режим)
	if старые == новые:
		return {"state": "same"}
	блоки: list[dict] = []
	for операция, i1, i2, j1, j2 in difflib.SequenceMatcher(None, старые, новые, autojunk=False).get_opcodes():
		if операция == "equal":
			блоки += [{"kind": "same", "text": т} for т in старые[i1:i2]]
		elif операция == "delete":
			блоки += [{"kind": "removed", "text": т} for т in старые[i1:i2]]
		elif операция == "insert":
			блоки += [{"kind": "added", "text": т} for т in новые[j1:j2]]
		else:
			блоки += _замена(старые[i1:i2], новые[j1:j2])
	итог = {"state": "changed", "mode": режим, "rewritten": _переписан(старые, новые, блоки), "blocks": _свернуть(блоки)}
	if итог["rewritten"]:
		# Переписанное показывают новым текстом целиком, прежний — по нажатию.
		итог["old"], итог["new"] = "\n\n".join(старые), "\n\n".join(новые)
	return итог


def сравнить(было: dict | None, стало: dict | None) -> dict:
	"""Разница двух снимков места (`agent_learning.snapshots`).

	Нет прежнего снимка — `unavailable`: замечание старше, чем кабинет начал
	их запоминать. Нет нынешнего — `missing`: места больше нет. У урока —
	по местам: изменённые, новые и пропавшие, в порядке урока.
	"""
	if было is None:
		return {"state": "unavailable"}
	if стало is None:
		return {"state": "missing"}
	if "places" not in было and "places" not in стало:
		return разница(было.get("text"), стало.get("text"), _режим(было, стало))
	старые, новые = было.get("places") or {}, стало.get("places") or {}
	места = []
	for адрес in [*новые, *(адрес for адрес in старые if адрес not in новые)]:
		прежнее, нынешнее = старые.get(адрес) or {}, новые.get(адрес) or {}
		итог = разница(прежнее.get("text"), нынешнее.get("text"), _режим(прежнее, нынешнее))
		if итог["state"] == "changed":
			места.append({"target": адрес, **итог})
	return {"state": "changed", "places": места} if места else {"state": "same"}


def _режим(было: dict, стало: dict) -> str:
	return стало.get("mode") or было.get("mode") or РЕЖИМ_ТЕКСТ


def _замена(старые: list[str], новые: list[str]) -> list[dict]:
	"""Абзацы на одном месте: похожие — правка по словам, непохожие —
	удалённый и новый; лишние — удалены или добавлены."""
	блоки: list[dict] = []
	for было, стало in zip(старые, новые, strict=False):
		части, похожесть = _по_словам(было, стало)
		if похожесть >= ПОРОГ_ПАРЫ:
			блоки.append({"kind": "changed", "parts": части})
		else:
			блоки += [{"kind": "removed", "text": было}, {"kind": "added", "text": стало}]
	блоки += [{"kind": "removed", "text": т} for т in старые[len(новые) :]]
	блоки += [{"kind": "added", "text": т} for т in новые[len(старые) :]]
	return блоки


def _по_словам(было: str, стало: str) -> tuple[list[list[str]], float]:
	"""Части абзаца и похожесть по словам. Похожесть — без пробелов: общие
	пробелы есть у любых двух абзацев и выдавали бы разные абзацы за правку."""
	старые, новые = _ЛЕКСЕМЫ.findall(было), _ЛЕКСЕМЫ.findall(стало)
	части: list[list[str]] = []
	for операция, i1, i2, j1, j2 in difflib.SequenceMatcher(None, старые, новые, autojunk=False).get_opcodes():
		if операция == "equal":
			_добавить(части, "=", "".join(старые[i1:i2]))
			continue
		_добавить(части, "-", "".join(старые[i1:i2]))
		_добавить(части, "+", "".join(новые[j1:j2]))
	слова = [[т for т in лексемы if not т.isspace()] for лексемы in (старые, новые)]
	return части, difflib.SequenceMatcher(None, *слова, autojunk=False).ratio()


def _добавить(части: list[list[str]], знак: str, текст: str) -> None:
	if not текст:
		return
	if части and части[-1][0] == знак:
		части[-1][1] += текст
	else:
		части.append([знак, текст])


def _переписан(старые: list[str], новые: list[str], блоки: list[dict]) -> bool:
	"""Общего меньше порога — по знакам, от длины большего из текстов. Из
	пустого или в пустое — не «переписан»: там всё новое или всё удалено."""
	if not старые or not новые:
		return False
	общее = sum(len(б["text"]) for б in блоки if б["kind"] == "same")
	общее += sum(len(текст) for б in блоки if б["kind"] == "changed" for знак, текст in б["parts"] if знак == "=")
	всего = max(sum(map(len, старые)), sum(map(len, новые)))
	return общее / всего < ПОРОГ_ПЕРЕПИСАН


def _свернуть(блоки: list[dict]) -> list[dict]:
	"""Неизменённые абзацы подряд — в одну строку, кроме контекста у правки.
	Свёрнутый один абзац места не экономит — его оставляем как есть."""
	итог: list[dict] = []
	i = 0
	while i < len(блоки):
		if блоки[i]["kind"] != "same":
			итог.append(блоки[i])
			i += 1
			continue
		j = i
		while j < len(блоки) and блоки[j]["kind"] == "same":
			j += 1
		серия = блоки[i:j]
		слева = 0 if i == 0 else КОНТЕКСТ
		справа = 0 if j == len(блоки) else КОНТЕКСТ
		if len(серия) - слева - справа >= 2:
			итог += серия[:слева]
			итог.append({"kind": "gap", "texts": [б["text"] for б in серия[слева : len(серия) - справа]]})
			итог += серия[len(серия) - справа :]
		else:
			итог += серия
		i = j
	return итог
