"""Сборка курса: вопросы квиза и готовность к публикации.

Здесь только хранение и нормализация. Педагогика — как формулировать вопрос,
на сколько уроков резать тему, что писать в директиве — живёт в агенте
куратора и в промпте авторского эндпоинта, а не в этом файле.
`Why:` приложение публикуется под AGPL; уехав сюда, эта логика перестанет
быть нашей.
"""

import frappe

from lms_frappe_app.agent_learning.errors import Отказ

ВАРИАНТОВ_МАКСИМУМ = 10

СЛИШКОМ_МНОГО_ВАРИАНТОВ = "too_many_options"
НЕИЗВЕСТНЫЙ_ТИП = "unknown_question_type"

#: Типы, которые сервер способен зачесть сам. `Open Ended` сюда не входит
#: намеренно: его проверка требует человека — см. `quiz._вопросы_квиза`.
ПРОВЕРЯЕМЫЕ_ТИПЫ = ("Choices", "User Input")


# --- вопросы ---


def создать_вопрос(вопрос: dict) -> tuple[str, str]:
	"""Заводит `LMS Question`, возвращает идентификатор и тип.

	Документ создаётся целиком, а не записью полей в базу: вся проверка
	вопроса у Frappe Learning живёт в `validate` (дубли вариантов, минимум
	два варианта, хотя бы один верный, образцы ответа для открытого), а в
	схеме не обязательно ни одно поле. Запись мимо документа обошла бы весь
	этот контроль молча.
	"""
	тип = вопрос.get("type") or "Choices"
	if тип not in ПРОВЕРЯЕМЫЕ_ТИПЫ:
		raise Отказ(
			НЕИЗВЕСТНЫЙ_ТИП,
			f"Тип вопроса должен быть одним из: {', '.join(ПРОВЕРЯЕМЫЕ_ТИПЫ)}",
			received=тип,
		)

	документ = frappe.new_doc("LMS Question")
	документ.question = (вопрос.get("text") or "").strip()
	документ.type = тип
	if тип == "Choices":
		_проставить_варианты(документ, вопрос.get("options") or [])
	else:
		_проставить_образцы(документ, вопрос.get("answers") or [])
	документ.insert()
	return документ.name, тип


def заменить_варианты(документ, варианты: list[dict]) -> None:
	"""Переписывает варианты вопроса целиком.

	Старые поля очищаются: правка «трёх вариантов на два» иначе оставила бы
	третий на месте, и вопрос ответил бы не тем, что видит куратор.
	"""
	_очистить(документ, ("option_{}", "is_correct_{}", "explanation_{}"))
	_проставить_варианты(документ, варианты)


def заменить_образцы(документ, ответы: list[str]) -> None:
	"""Переписывает образцы ответа целиком — по той же причине."""
	_очистить(документ, ("possibility_{}",))
	_проставить_образцы(документ, ответы)


def _очистить(документ, шаблоны: tuple[str, ...]) -> None:
	for номер in range(1, ВАРИАНТОВ_МАКСИМУМ + 1):
		for шаблон in шаблоны:
			документ.set(шаблон.format(номер), None)


def _проставить_варианты(документ, варианты: list[dict]) -> None:
	_проверить_количество(варианты)
	for номер, вариант in enumerate(варианты, start=1):
		документ.set(f"option_{номер}", (вариант.get("text") or "").strip())
		документ.set(f"is_correct_{номер}", 1 if вариант.get("correct") else 0)
		пояснение = (вариант.get("explanation") or "").strip()
		if пояснение:
			документ.set(f"explanation_{номер}", пояснение)


def _проставить_образцы(документ, ответы: list[str]) -> None:
	_проверить_количество(ответы)
	for номер, ответ in enumerate(ответы, start=1):
		документ.set(f"possibility_{номер}", (ответ or "").strip())


def _проверить_количество(элементы: list) -> None:
	if len(элементы) > ВАРИАНТОВ_МАКСИМУМ:
		raise Отказ(
			СЛИШКОМ_МНОГО_ВАРИАНТОВ,
			f"Frappe Learning хранит не более {ВАРИАНТОВ_МАКСИМУМ} вариантов в вопросе",
			received=len(элементы),
		)


# --- готовность к публикации ---

ПУСТОЙ_КУРС = "empty_course"
ПУСТОЙ_УРОК = "empty_lesson"
ВОПРОС_БЕЗ_ТЕКСТА = "blank_question"
КВИЗ_БЕЗ_ВОПРОСОВ = "empty_quiz"
НЕТ_ОПИСАНИЯ = "no_summary"

БЕЗ_ДИРЕКТИВЫ = "lesson_without_directive"
БЕЗ_КВИЗОВ = "course_without_quiz"


def проверить_готовность(курс: str) -> dict:
	"""Что мешает публикации и о чём стоит знать до неё.

	Возвращает всё разом, а не первую найденную беду: агент, получающий по
	одной ошибке за вызов, будет долбиться в публикацию по кругу, а куратор —
	смотреть на это.

	Проверяем только то, чего не проверяет Frappe Learning. Состав вариантов
	и наличие верного ответа он контролирует сам, в момент создания вопроса —
	см. `создать_вопрос`.
	"""
	from lms_frappe_app.agent_learning import quiz
	from lms_frappe_app.agent_learning.structure import уроки_курса

	мешает, стоит_знать = [], []

	if not frappe.db.get_value("LMS Course", курс, "short_introduction"):
		мешает.append({"code": НЕТ_ОПИСАНИЯ, "message": "Без краткого описания карточка в каталоге пустая"})

	уроки = уроки_курса(курс)
	if not уроки:
		мешает.append({"code": ПУСТОЙ_КУРС, "message": "В курсе нет ни одного урока"})

	с_квизом = 0
	for урок in уроки:
		if not (frappe.db.get_value("Course Lesson", урок, "body") or "").strip():
			мешает.append({"code": ПУСТОЙ_УРОК, "lesson": урок, "message": "Урок без материала"})

		квиз = quiz._квиз_урока(урок)
		if квиз:
			с_квизом += 1
			мешает += _беды_квиза(квиз, урок)

		if not frappe.db.exists("Agent Lesson Directive", {"lesson": урок, "is_active": 1}):
			стоит_знать.append(
				{
					"code": БЕЗ_ДИРЕКТИВЫ,
					"lesson": урок,
					"message": "Урок без директивы: агент поведёт занятие по одному материалу",
				}
			)

	if уроки and not с_квизом:
		стоит_знать.append(
			{"code": БЕЗ_КВИЗОВ, "message": "В курсе нет ни одного квиза: он зачтётся по прохождению уроков"}
		)

	return {"blocking": мешает, "warnings": стоит_знать}


def _беды_квиза(квиз: str, урок: str) -> list[dict]:
	вопросы = frappe.get_all("LMS Quiz Question", filters={"parent": квиз}, pluck="question")
	if not вопросы:
		return [
			{
				"code": КВИЗ_БЕЗ_ВОПРОСОВ,
				"lesson": урок,
				"message": "Квиз без вопросов: ученик упрётся в зачёт из ничего",
			}
		]

	# Единственное, чего Frappe Learning не ловит: пустой текст вопроса.
	# В схеме `LMS Question` не обязательно ни одно поле, включая сам вопрос.
	пустые = [
		вопрос
		for вопрос in вопросы
		if not (frappe.db.get_value("LMS Question", вопрос, "question") or "").strip()
	]
	return [
		{"code": ВОПРОС_БЕЗ_ТЕКСТА, "lesson": урок, "question": вопрос, "message": "Вопрос без текста"}
		for вопрос in пустые
	]
