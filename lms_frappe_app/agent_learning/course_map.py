"""Карта декомпозиции курса: проверка записи и сверка с курсом на платформе.

Карта — замысел курса: от результата через уровни, которые задаёт автор, к
урокам и блокам документа. Код знает только граф уровней и привязки к
сущностям платформы — урокам, их целям и блокам документа. Какие уровни есть и
что в них обязательно, приходит в данных карты флагами уровней: это методика,
и она остаётся содержанием курса, а не открытым кодом.

Модуль к базе не ходит: проверке отдают то, что прислал агент, сверке — то,
что лежит на платформе. Так обе части проверяются без курса в базе.

Устройство карты:

- `levels` — уровни слева направо; первый — корень;
- `nodes` — узлы; `parents` — узлы соседнего левого уровня, которым узел служит.
  Поэтому циклов в карте не бывает;
- `lessons` — план уроков; `nodes[].lesson` ссылается на ключ пункта плана, а
  пункт на урок платформы — полем `lesson`. Карту согласуют до сборки, когда
  уроков на платформе ещё нет;
- `blocks` — план блоков документа: какой урок собирает блок и какие критерии
  готовности должны дойти до подсказки агенту.
"""

from lms_frappe_app.agent_learning.doctype.agent_course_artifact.agent_course_artifact import (
	нормализовать_ключ,
)
from lms_frappe_app.agent_learning.errors import Отказ

НЕВЕРНАЯ_КАРТА = "invalid_map"

ПОЛЯ_УРОВНЯ = frozenset({"key", "title", "needs_children", "needs_lesson"})
ПОЛЯ_УЗЛА = frozenset({"id", "level", "text", "parents", "note", "tags", "lesson", "objective"})
ПОЛЯ_ПЛАНА = frozenset({"key", "title", "chapter", "lesson"})
ПОЛЯ_БЛОКА = frozenset({"artifact", "key", "title", "lesson", "criteria"})

#: Группы расхождений в том порядке, в каком их показывают.
ГРУППЫ = ("lessons", "objectives", "blocks", "integrity")


# --- запись ---


def нормализовать(levels: list, nodes: list, lessons: list, blocks: list) -> dict:
	"""Карта, проверенная и приведённая к одному виду, — или `Отказ(invalid_map)`.

	Отказ называет место (`where`): `nodes[T1].parents`, `lessons[u2].lesson`.
	С курсом карта здесь не сверяется — она может опережать сборку; сверка
	отдельно, в `сверить`.

	`Why:` неизвестное поле — тоже отказ, а не молчаливый пропуск: опечатка во
	флаге уровня иначе тихо выключила бы проверку, и агент решил бы, что карта
	цела.
	"""
	уровни = _уровни(levels)
	план = _план(lessons)
	узлы = _узлы(nodes, уровни, {пункт["key"] for пункт in план})
	блоки = _блоки(blocks, {пункт["key"] for пункт in план})
	return {"levels": уровни, "nodes": узлы, "lessons": план, "blocks": блоки}


def _уровни(сырые: list) -> list[dict]:
	if not isinstance(сырые, list) or not сырые:
		_отказ("levels", "Нужен хотя бы один уровень: первый — корень карты")
	уровни: list[dict] = []
	for индекс, сырой in enumerate(сырые):
		запись = _объект(сырой, f"levels[{индекс}]")
		ключ = _идентификатор(запись.get("key"))
		if not ключ:
			_отказ(f"levels[{индекс}].key", "У уровня нет ключа")
		место = f"levels[{ключ}]"
		_без_лишних(запись, ПОЛЯ_УРОВНЯ, место)
		if any(уровень["key"] == ключ for уровень in уровни):
			_отказ(место, f"Уровень «{ключ}» повторяется")
		уровни.append(
			{
				"key": ключ,
				"title": _обязательный_текст(запись.get("title"), f"{место}.title"),
				"needs_children": _флаг(запись.get("needs_children"), f"{место}.needs_children"),
				"needs_lesson": _флаг(запись.get("needs_lesson"), f"{место}.needs_lesson"),
			}
		)
	if уровни[-1]["needs_children"]:
		_отказ(
			f"levels[{уровни[-1]['key']}].needs_children",
			"Справа от последнего уровня уровней нет — детей у его узлов не будет",
		)
	return уровни


def _план(сырые) -> list[dict]:
	план: list[dict] = []
	привязки: dict[str, str] = {}
	for индекс, сырой in enumerate(_список(сырые, "lessons")):
		запись = _объект(сырой, f"lessons[{индекс}]")
		ключ = _идентификатор(запись.get("key"))
		if not ключ:
			_отказ(f"lessons[{индекс}].key", "У пункта плана нет ключа")
		место = f"lessons[{ключ}]"
		_без_лишних(запись, ПОЛЯ_ПЛАНА, место)
		if any(пункт["key"] == ключ for пункт in план):
			_отказ(место, f"Пункт плана «{ключ}» повторяется")
		урок = _идентификатор(запись.get("lesson"))
		if урок and урок in привязки:
			_отказ(f"{место}.lesson", f"Этот урок уже привязан к пункту «{привязки[урок]}»")
		if урок:
			привязки[урок] = ключ
		план.append(
			{
				"key": ключ,
				"title": _обязательный_текст(запись.get("title"), f"{место}.title"),
				"chapter": _текст(запись.get("chapter"), f"{место}.chapter"),
				"lesson": урок,
			}
		)
	return план


def _узлы(сырые, уровни: list[dict], ключи_плана: set[str]) -> list[dict]:
	номер_уровня = {уровень["key"]: номер for номер, уровень in enumerate(уровни)}
	узлы: list[dict] = []
	for индекс, сырой in enumerate(_список(сырые, "nodes")):
		запись = _объект(сырой, f"nodes[{индекс}]")
		ид = _идентификатор(запись.get("id"))
		if not ид:
			_отказ(f"nodes[{индекс}].id", "У узла нет идентификатора")
		место = f"nodes[{ид}]"
		_без_лишних(запись, ПОЛЯ_УЗЛА, место)
		if any(узел["id"] == ид for узел in узлы):
			_отказ(место, f"Узел «{ид}» повторяется")
		уровень = _идентификатор(запись.get("level"))
		if уровень not in номер_уровня:
			_отказ(f"{место}.level", f"Уровня «{уровень}» нет в levels")
		урок = _идентификатор(запись.get("lesson"))
		if урок and урок not in ключи_плана:
			_отказ(f"{место}.lesson", f"Пункта «{урок}» нет в плане уроков")
		узлы.append(
			{
				"id": ид,
				"level": уровень,
				"text": _обязательный_текст(запись.get("text"), f"{место}.text"),
				"parents": list(dict.fromkeys(_идентификаторы(запись.get("parents"), f"{место}.parents"))),
				"note": _текст(запись.get("note"), f"{место}.note"),
				"tags": _строки(запись.get("tags"), f"{место}.tags"),
				"lesson": урок,
				"objective": _флаг(запись.get("objective"), f"{место}.objective"),
			}
		)

	по_ид = {узел["id"]: узел for узел in узлы}
	for узел in узлы:
		номер = номер_уровня[узел["level"]]
		место = f"nodes[{узел['id']}].parents"
		if номер == 0 and узел["parents"]:
			_отказ(место, "У узла первого уровня родителей нет — он сам корень")
		for родитель in узел["parents"]:
			if родитель not in по_ид:
				_отказ(место, f"Узла «{родитель}» нет в карте")
			if номер_уровня[по_ид[родитель]["level"]] != номер - 1:
				_отказ(место, f"Узел «{родитель}» не с соседнего левого уровня")
	return узлы


def _блоки(сырые, ключи_плана: set[str]) -> list[dict]:
	блоки: list[dict] = []
	for индекс, сырой in enumerate(_список(сырые, "blocks")):
		запись = _объект(сырой, f"blocks[{индекс}]")
		документ = нормализовать_ключ(_идентификатор(запись.get("artifact")))
		if not документ:
			_отказ(f"blocks[{индекс}].artifact", "У блока нет документа")
		ключ = нормализовать_ключ(_идентификатор(запись.get("key")))
		if not ключ:
			_отказ(f"blocks[{индекс}].key", "У блока нет ключа")
		место = f"blocks[{документ}/{ключ}]"
		_без_лишних(запись, ПОЛЯ_БЛОКА, место)
		if any((блок["artifact"], блок["key"]) == (документ, ключ) for блок in блоки):
			_отказ(место, f"Блок «{ключ}» документа «{документ}» повторяется")
		урок = _идентификатор(запись.get("lesson"))
		if урок and урок not in ключи_плана:
			_отказ(f"{место}.lesson", f"Пункта «{урок}» нет в плане уроков")
		блоки.append(
			{
				"artifact": документ,
				"key": ключ,
				"title": _текст(запись.get("title"), f"{место}.title"),
				"lesson": урок,
				"criteria": _строки(запись.get("criteria"), f"{место}.criteria"),
			}
		)
	return блоки


def _отказ(место: str, сообщение: str):
	raise Отказ(НЕВЕРНАЯ_КАРТА, сообщение, where=место)


def _объект(значение, место: str) -> dict:
	if not isinstance(значение, dict):
		_отказ(место, "Ожидается объект")
	return значение


def _список(значение, место: str) -> list:
	if значение is None:
		return []
	if not isinstance(значение, list):
		_отказ(место, "Ожидается список")
	return значение


def _без_лишних(запись: dict, допустимые: frozenset, место: str) -> None:
	for поле in запись:
		if поле not in допустимые:
			_отказ(f"{место}.{поле}", f"Неизвестное поле «{поле}»; допустимы: {', '.join(sorted(допустимые))}")


def _идентификатор(значение) -> str | None:
	"""Ключ или идентификатор: строка или целое число — номера уроков в картах
	привычно пишут числами, и помнить, что сравнивать надо строку, агент не
	обязан."""
	if isinstance(значение, bool):
		return None
	if isinstance(значение, int):
		return str(значение)
	if isinstance(значение, str) and значение.strip():
		return значение.strip()
	return None


def _идентификаторы(значение, место: str) -> list[str]:
	собранное = []
	for элемент in _список(значение, место):
		ид = _идентификатор(элемент)
		if not ид:
			_отказ(место, "Ожидается список идентификаторов")
		собранное.append(ид)
	return собранное


def _текст(значение, место: str) -> str:
	if значение is None:
		return ""
	if not isinstance(значение, str):
		_отказ(место, "Ожидается строка")
	return значение.strip()


def _обязательный_текст(значение, место: str) -> str:
	текст = _текст(значение, место)
	if not текст:
		_отказ(место, "Текст пуст")
	return текст


def _строки(значение, место: str) -> list[str]:
	собранное = []
	for элемент in _список(значение, место):
		if not isinstance(элемент, str) or not элемент.strip():
			_отказ(место, "Ожидается список непустых строк")
		собранное.append(элемент.strip())
	return собранное


def _флаг(значение, место: str) -> bool:
	if значение is None:
		return False
	if isinstance(значение, bool) or значение in (0, 1):
		return bool(значение)
	_отказ(место, "Ожидается true или false")


# --- сверка ---


def сверить(карта: dict, уроки: list[dict], блоки: list[dict]) -> dict:
	"""Расхождения карты с курсом на платформе.

	`уроки` — уроки курса в порядке курса: `{id, title, chapter, objectives}`,
	где `objectives` — цели действующей директивы по строке. `блоки` — блоки
	действующих схем документа: `{artifact, key, title, lesson, hint}`.

	Ответ: сопоставление пунктов плана с уроками (`matches`), расхождения
	списком — у каждого группа, код, текст и ссылки на узлы, уроки и блоки, —
	счётчики по группам и узлы по меткам.
	"""
	соответствие = _сопоставить(карта["lessons"], уроки)
	по_группам = {
		"lessons": _расхождения_уроков(карта, уроки, соответствие),
		"objectives": _расхождения_целей(карта, уроки, соответствие),
		"blocks": _расхождения_блоков(карта, уроки, блоки, соответствие),
		"integrity": _расхождения_карты(карта),
	}
	расхождения = [
		{"group": группа, **расхождение} for группа in ГРУППЫ for расхождение in по_группам[группа]
	]
	метки: dict[str, list[str]] = {}
	for узел in карта["nodes"]:
		for метка in узел["tags"]:
			метки.setdefault(метка, []).append(узел["id"])
	return {
		"matches": соответствие,
		"discrepancies": расхождения,
		"counts": {**{группа: len(по_группам[группа]) for группа in ГРУППЫ}, "total": len(расхождения)},
		"tags": метки,
	}


def _сопоставить(план: list[dict], уроки: list[dict]) -> dict[str, str | None]:
	"""Пункт плана → урок платформы.

	Привязанный пункт — по привязке; урок, к которому он привязан, могли
	удалить, и тогда пункту пары нет. Непривязанный — по названию, среди уроков,
	которые ещё не заняты: карта опережает сборку, и привязывать каждый пункт
	агент не обязан.
	"""
	есть = {урок["id"] for урок in уроки}
	соответствие = {
		пункт["key"]: пункт["lesson"] if пункт["lesson"] in есть else None for пункт in план
	}
	занятые = set(соответствие.values())
	for пункт in план:
		if пункт["lesson"]:
			continue
		урок = next(
			(у["id"] for у in уроки if у["id"] not in занятые and у["title"] == пункт["title"]), None
		)
		if урок:
			соответствие[пункт["key"]] = урок
			занятые.add(урок)
	return соответствие


def _расхождения_уроков(карта: dict, уроки: list[dict], соответствие: dict) -> list[dict]:
	план = карта["lessons"]
	по_ид = {урок["id"]: урок for урок in уроки}
	расхождения = []
	for пункт in план:
		if not соответствие[пункт["key"]]:
			сообщение = (
				f"Урока «{пункт['title']}» больше нет на платформе"
				if пункт["lesson"]
				else f"Урока «{пункт['title']}» нет на платформе"
			)
			расхождения.append({"code": "missing", "plan_lesson": пункт["key"], "message": сообщение})
	занятые = set(соответствие.values())
	for урок in уроки:
		if урок["id"] not in занятые:
			расхождения.append(
				{"code": "extra", "lesson": урок["id"], "message": f"Урока «{урок['title']}» нет в карте"}
			)

	пары = [(пункт, по_ид[соответствие[пункт["key"]]]) for пункт in план if соответствие[пункт["key"]]]
	for пункт, урок in пары:
		ссылки = {"plan_lesson": пункт["key"], "lesson": урок["id"]}
		if урок["title"] != пункт["title"]:
			расхождения.append(
				{
					"code": "title",
					**ссылки,
					"expected": пункт["title"],
					"actual": урок["title"],
					"message": f"Урок называется «{урок['title']}», в карте — «{пункт['title']}»",
				}
			)
		if пункт["chapter"] and урок["chapter"] != пункт["chapter"]:
			расхождения.append(
				{
					"code": "chapter",
					**ссылки,
					"expected": пункт["chapter"],
					"actual": урок["chapter"],
					"message": f"Урок «{урок['title']}» в главе «{урок['chapter']}», в карте — в «{пункт['chapter']}»",
				}
			)

	место = {урок["id"]: номер for номер, урок in enumerate(уроки)}
	на_месте = _наибольшая_возрастающая([место[урок["id"]] for _, урок in пары])
	for номер, (пункт, урок) in enumerate(пары):
		if номер not in на_месте:
			расхождения.append(
				{
					"code": "order",
					"plan_lesson": пункт["key"],
					"lesson": урок["id"],
					"message": f"Урок «{урок['title']}» стоит не на том месте, что в карте",
				}
			)
	return расхождения


def _наибольшая_возрастающая(позиции: list[int]) -> set[int]:
	"""Номера элементов, которые остаются на месте.

	`Why:` переставленный урок сдвигает соседей, и сравнение «по позиции»
	пометило бы их все. Наибольшая возрастающая подпоследовательность — то,
	что стоит в порядке карты; остальное — ровно те уроки, которые сдвинули.
	"""
	длины = [1] * len(позиции)
	предки = [-1] * len(позиции)
	for i in range(len(позиции)):
		for j in range(i):
			if позиции[j] < позиции[i] and длины[j] + 1 > длины[i]:
				длины[i], предки[i] = длины[j] + 1, j
	if not позиции:
		return set()
	конец = max(range(len(позиции)), key=lambda i: длины[i])
	на_месте = set()
	while конец != -1:
		на_месте.add(конец)
		конец = предки[конец]
	return на_месте


def _расхождения_целей(карта: dict, уроки: list[dict], соответствие: dict) -> list[dict]:
	"""Цели урока на платформе против узлов-целей карты: дословно и по порядку."""
	по_ид = {урок["id"]: урок for урок in уроки}
	цели: dict[str, list[dict]] = {}
	for узел in карта["nodes"]:
		if узел["objective"] and узел["lesson"]:
			цели.setdefault(узел["lesson"], []).append(узел)
	расхождения = []
	for пункт in карта["lessons"]:
		ид = соответствие[пункт["key"]]
		if not ид:
			continue
		урок = по_ид[ид]
		узлы = цели.get(пункт["key"], [])
		ожидаемые = [узел["text"] for узел in узлы]
		на_платформе = урок["objectives"]
		нет = [цель for цель in ожидаемые if цель not in на_платформе]
		лишние = [цель for цель in на_платформе if цель not in ожидаемые]
		ссылки = {"plan_lesson": пункт["key"], "lesson": ид}
		if нет or лишние:
			расхождения.append(
				{
					"code": "mismatch",
					**ссылки,
					"missing": нет,
					"extra": лишние,
					"nodes": [узел["id"] for узел in узлы if узел["text"] in нет],
					"message": f"Цели урока «{урок['title']}» расходятся с картой: "
					f"нет {len(нет)}, лишних {len(лишние)}",
				}
			)
		elif ожидаемые != на_платформе:
			расхождения.append(
				{
					"code": "order",
					**ссылки,
					"nodes": [узел["id"] for узел in узлы],
					"message": f"Цели урока «{урок['title']}» стоят в другом порядке, чем в карте",
				}
			)
	return расхождения


def _расхождения_блоков(карта: dict, уроки: list[dict], блоки: list[dict], соответствие: dict) -> list[dict]:
	название = {урок["id"]: урок["title"] for урок in уроки}
	на_платформе = {(блок["artifact"], блок["key"]): блок for блок in блоки}
	расхождения = []
	for блок in карта["blocks"]:
		ссылки = {"artifact": блок["artifact"], "key": блок["key"]}
		есть = на_платформе.get((блок["artifact"], блок["key"]))
		if not есть:
			расхождения.append(
				{
					"code": "missing",
					**ссылки,
					"message": f"Блока «{блок['key']}» нет в схеме документа «{блок['artifact']}»",
				}
			)
			continue
		ожидаемый = соответствие.get(блок["lesson"]) if блок["lesson"] else None
		if ожидаемый and ожидаемый != есть["lesson"]:
			фактический = название.get(есть["lesson"], "никаким") if есть["lesson"] else "никаким"
			расхождения.append(
				{
					"code": "lesson",
					**ссылки,
					"expected": ожидаемый,
					"actual": есть["lesson"],
					"message": f"Блок «{блок['key']}» собирается уроком «{фактический}», "
					f"в карте — «{название[ожидаемый]}»",
				}
			)
		подсказка = _сжать(есть.get("hint") or "")
		нет = [критерий for критерий in блок["criteria"] if _сжать(критерий) not in подсказка]
		if нет:
			расхождения.append(
				{
					"code": "criteria",
					**ссылки,
					"missing": нет,
					"message": f"В подсказку блока «{блок['key']}» не дошли критерии: {len(нет)}",
				}
			)
	в_плане = {(блок["artifact"], блок["key"]) for блок in карта["blocks"]}
	for блок in блоки:
		if (блок["artifact"], блок["key"]) not in в_плане:
			расхождения.append(
				{
					"code": "extra",
					"artifact": блок["artifact"],
					"key": блок["key"],
					"message": f"Блока «{блок['key']}» документа «{блок['artifact']}» нет в карте",
				}
			)
	return расхождения


def _сжать(текст: str) -> str:
	"""Текст для поиска критерия в подсказке: без регистра и лишних пробелов."""
	return " ".join(текст.casefold().split())


def _расхождения_карты(карта: dict) -> list[dict]:
	"""Целостность самой карты; что обязательно, говорят флаги уровней."""
	уровни = карта["levels"]
	номер_уровня = {уровень["key"]: номер for номер, уровень in enumerate(уровни)}
	дети: dict[str, list[str]] = {}
	for узел in карта["nodes"]:
		for родитель in узел["parents"]:
			дети.setdefault(родитель, []).append(узел["id"])

	достижимые = set()
	очередь = [узел["id"] for узел in карта["nodes"] if номер_уровня[узел["level"]] == 0]
	while очередь:
		ид = очередь.pop()
		if ид not in достижимые:
			достижимые.add(ид)
			очередь.extend(дети.get(ид, []))

	расхождения = []
	for узел in карта["nodes"]:
		if узел["id"] not in достижимые:
			расхождения.append(
				{
					"code": "orphan",
					"node": узел["id"],
					"message": f"«{узел['text']}»: нет пути к уровню «{уровни[0]['title']}»",
				}
			)
	for узел in карта["nodes"]:
		номер = номер_уровня[узел["level"]]
		if уровни[номер]["needs_children"] and not дети.get(узел["id"]):
			расхождения.append(
				{
					"code": "unexpanded",
					"node": узел["id"],
					"message": f"«{узел['text']}»: на уровне «{уровни[номер + 1]['title']}» у него ничего нет",
				}
			)
	for узел in карта["nodes"]:
		if уровни[номер_уровня[узел["level"]]]["needs_lesson"] and not узел["lesson"]:
			расхождения.append(
				{"code": "no_lesson", "node": узел["id"], "message": f"«{узел['text']}»: урок не назначен"}
			)
	return расхождения
