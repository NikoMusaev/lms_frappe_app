"""Общее устройство директив: версии и «действующая ровно одна».

`Why:` инвариант жил в контроллере урочной директивы и **отдельно** в методе
авторинга, который деактивировал прошлые версии сам. Второй адресат директив —
курс — превратил бы две копии в четыре, а разъехавшиеся копии означают, что
агент однажды получит две действующие директивы разом и молча возьмёт любую.
"""

import frappe
from frappe.model.document import Document


class ВерсионированнаяДиректива(Document):
	"""Директива, которую переписывают чаще, чем то, к чему она приложена.

	Наследник объявляет `ПОЛЕ_ВЛАДЕЛЬЦА` — имя ссылки на урок или курс.
	"""

	ПОЛЕ_ВЛАДЕЛЬЦА: str

	def before_insert(self):
		# Версию всегда считает система: поле read_only, и переданное значение
		# намеренно затирается. Иначе импорт директивы с проставленной версией
		# тихо создаст вторую «версию 1» на того же владельца.
		self.version = self._следующая_версия()

	def validate(self):
		if self.version < 1:
			frappe.throw(frappe._("Версия директивы начинается с единицы"))

	def on_update(self):
		if self.is_active:
			self._снять_с_действия_прочие()

	@property
	def _владелец(self) -> str:
		return self.get(self.ПОЛЕ_ВЛАДЕЛЬЦА)

	def _следующая_версия(self) -> int:
		прошлые = frappe.get_all(
			self.doctype,
			filters={self.ПОЛЕ_ВЛАДЕЛЬЦА: self._владелец},
			pluck="version",
			order_by="version desc",
			limit=1,
		)
		return (прошлые[0] if прошлые else 0) + 1

	def _снять_с_действия_прочие(self) -> None:
		прочие = frappe.get_all(
			self.doctype,
			filters={
				self.ПОЛЕ_ВЛАДЕЛЬЦА: self._владелец,
				"is_active": 1,
				"name": ("!=", self.name),
			},
			pluck="name",
		)
		for имя in прочие:
			# set_value, а не сохранение документа: чужие версии трогаем точечно
			# и без повторного запуска хуков, иначе получим рекурсию.
			frappe.db.set_value(self.doctype, имя, "is_active", 0, update_modified=False)


def записать(doctype: str, поле: str, владелец: str, содержание: dict) -> dict:
	"""Заводит новую действующую версию директивы.

	Прошлые версии не удаляются, а снимаются с действия контроллером: занятие,
	идущее прямо сейчас, уже получило свою директиву, и стирать её из истории
	значит потерять основание выставленного зачёта.
	"""
	документ = frappe.get_doc(
		{"doctype": doctype, поле: владелец, "is_active": 1, **содержание}
	).insert()
	return {"id": документ.name, поле: владелец, "version": документ.version}
