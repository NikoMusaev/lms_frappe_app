import frappe
from frappe.model.document import Document

#: Имя доктайпа и единственной записи: Single-доктайп зовётся сам собой.
НАСТРОЙКИ = "Agent Learning Settings"


class AgentLearningSettings(Document):
	pass


def настройка(поле: str, запасное=None):
	"""Значение поля настроек платформы; пустое — запасное.

	`Why:` параметры методики меняются из админки, иначе хранение схем во
	Frappe не даёт ничего, кроме лишнего слоя. Но настройка может быть не
	заполнена — на новом стенде, после ручной очистки поля, — и тогда работает
	запасное значение из кода: методика не должна ломаться из-за пустой строки
	в таблице. Чтение идёт через кеш документов: за запрос к базе платит
	первое обращение, остальные берут готовое.
	"""
	return frappe.get_cached_value(НАСТРОЙКИ, НАСТРОЙКИ, поле) or запасное


#: Запасное число пробных уроков веб-чата, если настройки почему-то недоступны.
ПРОБНЫХ_УРОКОВ = 2


def пробных_уроков() -> int:
	"""Сколько уроков ученик проходит в веб-чате платформы без своего агента.

	`Why:` число читали из настройки дважды — метод, который лимит проверяет,
	и страница `/agent`, которая его обещает. Страница ради этого импортировала
	константу из API-слоя, то есть знала про методы контракта ради одной цифры;
	разойдясь, обещание и проверка показали бы ученику разное.
	"""
	return настройка("web_demo_lessons", ПРОБНЫХ_УРОКОВ)


#: Путь веб-чата у сервиса агента.
ПУТЬ_ЧАТА = "/chat"


def адрес_сервиса() -> str:
	"""База адресов сервиса агента из настроек, без завершающей косой черты.

	`Why:` пусто — сервиса агента у этой установки нет, и платформа не зовёт
	туда, где никто не ответит: страница `/agent` не показывает адресов и
	приглашения в веб-чат, а урок ведёт на `/agent`, а не в чат. Живёт здесь,
	а не у страницы: адрес нужен и ей, и методам API, а API не импортирует
	страницы.
	"""
	return (настройка("agent_service_url") or "").strip().rstrip("/")
