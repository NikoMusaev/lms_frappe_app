"""Страница «Подключить агента»: адреса MCP и шаги подключения под роль.

Здесь только механика платформы — куда подключаться и как войти. Чему учить
и как вести занятие, страница не знает: это закрытая часть.
"""

import frappe

from lms_frappe_app.agent_learning.doctype.agent_learning_settings.agent_learning_settings import (
	настройка,
	пробных_уроков,
)
from lms_frappe_app.site_navigation import шапка_платформы

no_cache = 1

ИСХОДНИКИ = "https://github.com/lms-high-time/learning-app"
#: Frappe пускает не больше стольких регистраций OAuth-клиентов; клиент
#: регистрируется при каждом новом подключении.
ЛИМИТ_РЕГИСТРАЦИЙ = "5 подключений за 10 минут"
РОЛИ_КУРАТОРА = {"Course Creator", "Moderator"}

#: Пути сервиса агента под роль. База адреса — настройка платформы: сервис
#: живёт за своей границей и на другой установке может стоять где угодно.
ПУТЬ_УЧЕНИКА = "/mcp"
ПУТЬ_КУРАТОРА = "/authoring"
ПУТЬ_ЧАТА = "/chat"


def адрес_сервиса() -> str:
	"""База адресов подключения из настроек, без завершающей косой черты.

	`Why:` пусто — сервиса агента у этой установки нет, и страница не зовёт
	туда, где никто не ответит: блоки с адресами и приглашение в веб-чат
	просто не показываются.
	"""
	return (настройка("agent_service_url") or "").strip().rstrip("/")


def сведения(пользователь: str) -> dict:
	"""Что показать на странице этому пользователю."""
	сервис = адрес_сервиса()
	гость = пользователь == "Guest"
	роли = set() if гость else set(frappe.get_roles(пользователь))
	куратор = bool(роли & РОЛИ_КУРАТОРА)
	подключения = []
	if сервис and not гость:
		подключения.append(
			{
				"role": "student",
				"title": "Учиться",
				"url": f"{сервис}{ПУТЬ_УЧЕНИКА}",
				"first_step": "Попросите агента показать ваши курсы и начать урок.",
			}
		)
	if сервис and куратор:
		подключения.append(
			{
				"role": "curator",
				"title": "Собирать курсы",
				"url": f"{сервис}{ПУТЬ_КУРАТОРА}",
				"first_step": _первый_шаг_куратора(),
			}
		)
	return {
		"service_url": сервис,
		"is_guest": гость,
		"is_curator": куратор,
		"connections": подключения,
		"login_url": "/login?redirect-to=/agent",
		"registration_limit": ЛИМИТ_РЕГИСТРАЦИЙ,
		"source_url": ИСХОДНИКИ,
		# Путь без своего агента: пробные уроки в веб-чате. Число — из той же
		# настройки, которой лимит проверяет `start_lesson`.
		"chat_url": f"{сервис}{ПУТЬ_ЧАТА}" if сервис else "",
		"web_demo_lessons": пробных_уроков(),
	}


def _первый_шаг_куратора() -> str:
	"""Совет куратору начать с инструмента-гайда — если такой инструмент есть.

	`Why:` имя инструмента — часть контракта сервиса агента, а не платформы.
	Не задано — совета нет: обещать вызов, которого у клиента не окажется,
	хуже, чем промолчать.
	"""
	гайд = (настройка("authoring_guide_tool") or "").strip()
	if not гайд:
		return ""
	return (
		f"Первым вызовом попросите агента вызвать {гайд}: "
		"это порядок сборки и правила платформы."
	)


def get_context(context):
	context.no_breadcrumbs = True
	шапка_платформы(context)
	context.title = "Подключить агента"
	context.update(сведения(frappe.session.user))
	return context
